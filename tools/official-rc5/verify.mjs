import {readFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {verifyMain} from '../rc5-valve/verify-main.mjs';
const root=resolve(import.meta.dirname,'../..');
const release=join(root,'firmware/releases/nature_touch_v3_rc5_d5_routing_20261105');
const build=JSON.parse(readFileSync(join(release,'build-manifest.json'),'utf8'));
const main=verifyMain();
const version='3.0.0-rc5-d5route',timeline='25s-4c1e4167',revision='5356f28e';
const expectedMain='fe81638aed3eb500ea8c3e76a6d7a1f98864660ae77094f9b8e1f133ec04bff9';
const expectedHex='3f7a1edf383dab1d11367aa39d30c445f2e5b367b52fc5767fd6d74326c5e09c';
const hash=p=>createHash('sha256').update(readFileSync(p)).digest('hex');
assert.equal(build.version,version);assert.equal(build.protocolVersion,2);
assert.equal(build.timelineVersion,timeline);assert.equal(build.sourceRevision,revision);
assert.equal(build.main.path,'desktop/out-exhibition-rc5-valve');assert.equal(build.main.entry,'main/bootstrap.cjs');
assert.equal(build.main.version,version);assert.equal(build.main.sha256,expectedMain);
assert.equal(main.entries.RC5.version,version);assert.equal(main.entries.RC5.file,'main.js');assert.equal(main.entries.RC5.sha256,expectedMain);
assert.equal(build.main.checksummedFiles,24);assert.equal(Object.keys(main.checksums).length,24);
for(const p of ['main/main.js','main/bootstrap.cjs','main/startup-config.json','preload/preload.cjs','renderer/index.html','renderer/projector.html'])assert.ok(main.checksums[p],`Missing release asset: ${p}`);
assert.equal(hash(join(main.absoluteOutput,'main/main.js')),expectedMain);
assert.equal(build.firmware.hex,'real/nature_touch_unified.ino.hex');assert.equal(build.firmware.sha256,expectedHex);
assert.equal(hash(join(release,build.firmware.hex)),expectedHex);
const source=readFileSync(join(main.absoluteOutput,'main/main.js'),'utf8');
assert.ok(source.includes(`const EXHIBITION_FIRMWARE_TARGET = { firmwareVersion: "${version}", timelineVersion: "${timeline}", sourceRevision: "${revision}" };`));
const config=JSON.parse(readFileSync(join(main.absoluteOutput,'main/startup-config.json'),'utf8'));
assert.deepEqual(config.entries.RC5,main.entries.RC5);
assert.ok(readFileSync(join(release,'source/nature_touch_unified/firmware-version.h'),'utf8').includes(`NATURE_TOUCH_FIRMWARE_VERSION "${version}"`));
console.log(JSON.stringify({result:'PASS',release:'RC5',version,protocol:2,main:main.absoluteEntry,mainSha256:expectedMain,hexSha256:expectedHex,resources:Object.keys(main.checksums).length,serialOpened:false,started:false}));
